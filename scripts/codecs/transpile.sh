#!/bin/bash
# Regenerates crates/lean11-codecs/src/generated/*.rs: wimlib's compressors translated to Rust with c2rust.
# The generated code is bit-identical in output to wimlib (checked with the codec comparison bench).
#
# Needs: git, clang-19, llvm-19-dev, libclang-19-dev, bear, autoconf/automake/libtool, pkg-config,
#        gcc-aarch64-linux-gnu + libc6-dev-arm64-cross (headers for the aarch64 translation),
#        c2rust 0.22.1 (LLVM_CONFIG_PATH=/usr/lib/llvm-19/bin/llvm-config cargo install --locked c2rust).
# Translating for aarch64 selects wimlib's portable C paths (no x86 inline assembly); -DNDEBUG drops
# glibc assertion calls. Usage: transpile.sh <work dir>
set -euo pipefail
WORK=${1:?work dir}; TAG=v1.14.5
HERE=$(cd "$(dirname "$0")" && pwd); OUT=$HERE/../../crates/lean11-codecs/src/generated
FILES="compress_common divsufsort lcpit_matchfinder lzms_common lzms_compress lzx_common lzx_compress xpress_compress decompress_common lzms_decompress lzx_decompress xpress_decompress"
mkdir -p "$WORK"; cd "$WORK"
[ -d wimlib ] || git clone -q --branch $TAG --depth 1 https://github.com/ebiggers/wimlib.git
cd wimlib
if [ ! -f compile_commands.json ]; then
  ./bootstrap > /dev/null 2>&1
  ./configure --without-fuse --without-ntfs-3g --disable-static CC=clang-19 > /dev/null
  bear -- make -j"$(nproc)" > /dev/null
fi
for f in $FILES; do
  mkdir -p "$WORK/cc-$f"
  python3 - "$f" "$WORK/cc-$f/compile_commands.json" <<'PY'
import json, sys
name, dest = sys.argv[1], sys.argv[2]
sel = [e for e in json.load(open("compile_commands.json")) if e["file"].endswith("/" + name + ".c")]
for e in sel:
    a = [x for x in e["arguments"] if x != "-g"]
    e["arguments"] = [a[0], "--target=aarch64-linux-gnu"] + a[1:] + ["-DNDEBUG"]
json.dump(sel, open(dest, "w"))
PY
  rm -rf "$WORK/out-$f"
  c2rust transpile "$WORK/cc-$f/compile_commands.json" -o "$WORK/out-$f" > "$WORK/log-$f" 2>&1
  src=$(find "$WORK/out-$f" -name "$f.rs")
  lic=$(sed -n 1,40p "src/$f.c" | grep -q "Lesser General Public" && echo "LGPL-2.1-or-later" || echo "MIT")
  {
    echo "// SPDX-License-Identifier: $lic"
    echo "// Generated by scripts/codecs/transpile.sh (c2rust 0.22.1) from wimlib $TAG src/$f.c. Do not edit."
    # c2rust ran on LP64 Linux: C long is 64 bit there, but only 32 bit on Windows (LLP64), so the
    # generated code gets fixed-width types (the same as on Linux and macOS)
    sed -e '/^#!\[feature/d' \
        -e 's/pub const WORDBYTES: ::core::ffi::c_ulong = ::core::mem::size_of::<machine_word_t>();/pub const WORDBYTES: ::core::ffi::c_ulong = ::core::mem::size_of::<machine_word_t>() as ::core::ffi::c_ulong;/' \
        -e 's/::core::ffi::c_ulonglong/u64/g; s/::core::ffi::c_ulong\b/u64/g; s/::core::ffi::c_long\b/i64/g' \
        "$src"
  } > "$OUT/$f.rs"
  echo "$f: $(wc -l < "$OUT/$f.rs") lines ($lic)"
done
