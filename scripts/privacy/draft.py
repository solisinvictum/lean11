#!/usr/bin/env python3
"""Developer tool: turns expand.py's worksheet into a DRAFT catalog in lean11's format, so that
`lean11 privacy verify --catalog draft.toml <image>` checks the whole source collection at once. The draft is a
worksheet for curation; the shipped catalog (crates/lean11-core/data/privacy.toml) is written by hand.

usage: draft.py ops.json > draft.toml
"""
import json
import re
import sys


def slug(s, n=60):
    s = re.sub(r"[`\"'()]", "", s.lower())
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s[:n].rstrip("-")


def tq(s):
    """TOML literal string (single quotes) when possible, else basic string."""
    if "'" not in s and "\n" not in s:
        return f"'{s}'"
    return json.dumps(s)


LEVEL = {"standard": "recommended", "strict": "strict"}


def convert(o):
    """source leaf op -> (toml inline table | None, todo text | None)"""
    op = o["op"]
    if op == "SetRegistryValue":
        if o.get("evaluateDataAsPowerShell"):
            return None, f"SetRegistryValue with PowerShell data {o['keyPath']}!{o['valueName']} = {o['data']}"
        t = o["dataType"]
        data = o.get("data", "")
        if t == "REG_DWORD":
            val = f"dword = {int(data, 0)}"
        elif t == "REG_SZ":
            val = f"sz = {tq(data)}"
        elif t == "REG_MULTI_SZ":
            parts = [p for p in re.split(r"\\0|\n", data) if p]
            val = "multi_sz = [" + ", ".join(tq(p) for p in parts) + "]"
        else:
            return None, f"type {t}"
        return f"{{ reg = {tq(o['keyPath'])}, name = {tq(o['valueName'])}, {val} }}", None
    if op == "DeleteRegistryValue":
        return f"{{ reg = {tq(o['keyPath'])}, name = {tq(o['valueName'])}, delete = true }}", None
    if op in ("SoftDeleteRegistryKey", "DeleteRegistryKey"):
        return f"{{ reg = {tq(o['keyPath'])}, delete_key = true }}", None
    if op in ("DisableService", "DisableServiceInRegistry"):
        n = o["serviceName"]
        if "*" in n:
            return None, f"per-user service instances {n}"
        return f"{{ service = {tq(n)}, start = 4 }}", None
    if op == "DisableScheduledTask":
        p = o["taskPathPattern"].rstrip("\\") + "\\" + o["taskNamePattern"]
        if any(c in p for c in "*?{}"):
            return None, f"task pattern {p}"
        return f"{{ task = {tq(p)} }}", None
    if op == "BlockViaHostsFile":
        return f"{{ hosts = [{tq(o['domain'])}] }}", None
    if op in ("CreateRegistryKey", "StopService", "StartService", "TerminateRunningProcess"):
        return None, None  # live-system bookkeeping, nothing to do offline
    return None, f"{op} {json.dumps({k: v for k, v in o.items() if k not in ('op', 'code', 'revertCode')}, ensure_ascii=False)[:200]}"


def main():
    scripts = json.load(open(sys.argv[1]))
    cats, out, seen = {}, [], set()
    for s in scripts:
        path = s["path"]
        for i in range(len(path)):
            cid = slug("-".join(path[: i + 1]), 80)
            if cid not in cats:
                cats[cid] = (path[i], slug("-".join(path[:i]), 80) if i else None)
        cat = slug("-".join(path), 80)
        sid = slug(s["name"])
        while sid in seen:
            sid += "-x"
        seen.add(sid)
        ops, todos = [], []
        for o in s["ops"]:
            t, todo = convert(o)
            if t:
                ops.append(t)
            if todo:
                todos.append(todo)
        out.append((sid, cat, s, ops, todos))
    print("# DRAFT generated by scripts/privacy/draft.py - not the shipped catalog\n")
    for cid, (title, parent) in cats.items():
        print(f"[[category]]\nid = {tq(cid)}\ntitle = {tq(title)}")
        if parent:
            print(f"parent = {tq(parent)}")
        print()
    for sid, cat, s, ops, todos in out:
        if not ops:
            print(f"# SKIPPED {sid}: " + "; ".join(todos or ["no offline ops"]) + "\n")
            continue
        print(f"[[setting]]\nid = {tq(sid)}\ncategory = {tq(cat)}\ntitle = {tq(s['name'])}")
        print(f"description = 'draft'\nlevel = '{LEVEL.get(s['recommend'], 'optional')}'\nverified = 'draft'")
        print(f"sources = [{tq(s['name'])}]")
        for t in todos:
            print(f"# TODO {t}")
        print("ops = [\n  " + ",\n  ".join(ops) + ",\n]\n")


if __name__ == "__main__":
    main()
